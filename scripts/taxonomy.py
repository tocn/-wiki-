def parent_of(title):
    """子页面的父页面标题;顶层页面返回 None。"""
    t = title or ""
    return t.rsplit("/", 1)[0] if "/" in t else None


def resolve_with_inherit(cats_by_page, title2cat, pageid, title):
    """带父页面继承的判定封装。"""
    pt = parent_of(title)
    pc = title2cat.get(pt) if pt else None
    return resolve(cats_by_page.get(pageid, []), title,
                   parent_cats=pc, parent_title=pt)


def coverage(index_rows, cats_by_page, title2cat=None):
    """统计映射覆盖率与未映射分类,用于验证分类法完备性。"""
    title2cat = title2cat or {}
    freq = Counter()
    for r in index_rows:
        for c in content_categories(cats_by_page.get(r["pageid"], [])):
            freq[c] += 1
    unmapped = {c: n for c, n in freq.items() if c not in CATEGORY_MAP}
    total = sum(freq.values())
    covered = total - sum(unmapped.values())
    buckets = Counter()
    sources = Counter()
    for r in index_rows:
        folder, src = resolve_with_inherit(cats_by_page, title2cat, r["pageid"], r.get("title", ""))
        buckets[folder] += 1
        sources[src] += 1
    return {
        "distinct": len(freq), "mapped": len(freq) - len(unmapped),
        "total_usage": total, "covered_usage": covered,
        "coverage_pct": (covered / total * 100) if total else 100.0,
        "unmapped": unmapped, "buckets": buckets, "sources": sources,
    }
