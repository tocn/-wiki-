def content_categories(cats):
    """剔除维护性分类,只保留内容分类。"""
    return [c for c in (cats or []) if c not in MAINT_CATS]


# 标题关键词兜底。
# 缘起:部分页面在源站只挂了维护性分类(如「待审核」+「待审核攻略」),
# 剔除维护分类后就没有内容归属了。此类页面按标题关键词兜底比丢进「未分类」可用。
# 只收录高精度关键词,宁可漏判不做误判;命中结果会在 index 中标记来源为 title。
TITLE_HINTS = (
    ("攻略", "攻略"),
    ("语音", "角色"),
    ("食谱", "道具材料"),
    ("圣遗物", "圣遗物"),
)


def folder_for(cats):
    """按源站分类判定归档大类;无法判定时返回 None。"""
    for c in content_categories(cats):
        if c in CATEGORY_MAP:
            return CATEGORY_MAP[c]
    return None


def folder_by_title(title):
    """源站分类缺位时,按标题关键词兜底判定;无命中返回 None。"""
    for kw, folder in TITLE_HINTS:
        if kw in (title or ""):
            return folder
    return None


def resolve(cats, title):
    """
    综合判定归档大类。返回 (folder, source):
      source = "wiki"  依据源站分类(权威)
               "title" 依据标题关键词兜底
               "none"  仍无法判定,归入未分类
    """
    f = folder_for(cats)
    if f:
        return f, "wiki"
    f = folder_by_title(title)
    if f:
        return f, "title"
    return UNCLASSIFIED, "none"


def folder_or_unclassified(cats):
    return folder_for(cats) or UNCLASSIFIED


def coverage(index_rows, cats_by_page):
    """统计映射覆盖率与未映射分类,用于验证分类法完备性。"""
    freq = Counter()
    for r in index_rows:
        for c in content_categories(cats_by_page.get(r["pageid"], [])):
            freq[c] += 1
    unmapped = {c: n for c, n in freq.items() if c not in CATEGORY_MAP}
    total = sum(freq.values())
    covered = total - sum(unmapped.values())
    buckets = Counter()
    sources = Counter()
    for r in index_rows:
        folder, src = resolve(cats_by_page.get(r["pageid"], []), r.get("title", ""))
        buckets[folder] += 1
        sources[src] += 1
    return {
        "distinct": len(freq), "mapped": len(freq) - len(unmapped),
        "total_usage": total, "covered_usage": covered,
        "coverage_pct": (covered / total * 100) if total else 100.0,
        "unmapped": unmapped, "buckets": buckets, "sources": sources,
    }
